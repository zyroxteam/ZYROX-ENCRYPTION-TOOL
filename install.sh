#!/tmp/prefix/bin/bash
# ============================================================================
#  ZYROX ENCRYPTION — install.sh
#  'zyrox' command install karta hai, taaki kahin se bhi chalayein:
#       zyrox /sdcard/myapp.apk
# ============================================================================
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

c()  { printf '\033[1;33m%s\033[0m\n' "$*"; }
ok() { printf '\033[1;32m[OK] %s\033[0m\n' "$*"; }
er() { printf '\033[1;31m[X] %s\033[0m\n' "$*"; }
warn(){ printf '\033[1;35m[!] %s\033[0m\n' "$*"; }

chmod +x "$HERE/bin/zyrox" "$HERE/setup.sh" "$HERE/zyrox.py" "$HERE/zyrox-verify.py" 2>/dev/null || true

# Termux / Linux me PATH bin folder choose karo
BIN=""
if [ -n "${PREFIX:-}" ] && [ -d "$PREFIX/bin" ]; then
    BIN="$PREFIX/bin"
elif [ -d "$HOME/.local/bin" ]; then
    BIN="$HOME/.local/bin"
else
    mkdir -p "$HOME/.local/bin" && BIN="$HOME/.local/bin"
fi

# environment ke hisaab se sahi shebang (Termux ka bash path alag hota hai)
if [ -n "${PREFIX:-}" ] && [ -x "$PREFIX/bin/bash" ]; then
    SHEBANG="#!$PREFIX/bin/bash"
elif [ -x /bin/bash ]; then
    SHEBANG="#!/bin/bash"
else
    SHEBANG="#!/usr/bin/env bash"
fi

c "[*] 'zyrox' command install ho raha hai: $BIN/zyrox"
# chhota shim likho (updates ke liye asli files repo me hi rehti hain)
cat > "$BIN/zyrox" <<SHIM
$SHEBANG
# ZYROX ENCRYPTION launcher (auto-generated by install.sh)
exec bash "$HERE/bin/zyrox" "\$@"
SHIM
chmod +x "$BIN/zyrox" 2>/dev/null || true

if [ -s "$BIN/zyrox" ]; then
    ok "installed: $BIN/zyrox  (launcher -> $HERE/bin/zyrox)"
else
    er "install fail — check permissions: $BIN"
    exit 1
fi

# PATH check
case ":$PATH:" in
    *":$BIN:"*) ok "PATH me pehle se hai" ;;
    *)
        warn "$BIN aapke PATH me nahi hai"
        echo "     chalao:  echo 'export PATH=\"$BIN:\$PATH\"' >> ~/.bashrc && source ~/.bashrc"
        ;;
esac

# toolchain check
if [ ! -f "$HERE/tool/apktool.jar" ]; then
    warn "toolchain abhi install nahi hua — setup chala raha hoon…"
    bash "$HERE/setup.sh" || { er "setup fail"; exit 1; }
fi

# storage permission (Termux)
if command -v termux-setup-storage >/dev/null 2>&1 && [ ! -d "$HOME/storage" ]; then
    warn "storage access nahi mila — 'termux-setup-storage' chalayein (popup me Allow karein)"
fi

echo
ok "READY ✅"
echo
echo "  Ab kahin se bhi chalayein:"
echo "     zyrox /sdcard/myapp.apk"
echo "     zyrox /sdcard/myapp.apk --keys my-release.jks --ks-pass PASS --alias myalias"
echo "     zyrox /sdcard/myapp.apk --info"
echo "     zyrox --version"
echo
echo "  Output:  $HERE/out/  (+ /sdcard/Download/zyrox/  agar --to-storage)"
echo
